"""Run the full cleaning pipeline: raw CSVs -> validated clean CSVs.

Run from the project root:
    python -m src.cleaning.pipeline

Reads   data/raw/*.csv          (never modified)
Writes  data/processed/*.csv    (one clean file per table)
        reports/cleaning_log.md (what changed, row counts before/after)
"""
from __future__ import annotations

import logging
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

from src.cleaning.cleaners import (
    CleaningLog,
    clean_categories,
    clean_customers,
    clean_geolocation,
    clean_order_items,
    clean_orders,
    clean_payments,
    clean_products,
    clean_reviews,
    clean_sellers,
)
from src.cleaning.validation import DataValidationError, assert_valid
from src.config import PROCESSED_DIR, REPORTS_DIR
from src.ingestion.loader import MissingDatasetError, load_all_raw
from src.ingestion.quality_report import df_to_markdown

logger = logging.getLogger(__name__)

# Clean output file names (used by Module C to load MySQL).
OUTPUT_FILES = {
    "customers": "customers.csv",
    "sellers": "sellers.csv",
    "geolocation": "geolocation.csv",
    "category_translation": "product_categories.csv",
    "products": "products.csv",
    "orders": "orders.csv",
    "order_items": "order_items.csv",
    "payments": "payments.csv",
    "reviews": "reviews.csv",
}


def clean_all(raw: dict[str, pd.DataFrame], log: CleaningLog) -> dict[str, pd.DataFrame]:
    """Apply every table cleaner. Order matters only for products (needs categories)."""
    categories = clean_categories(raw["category_translation"], log)
    return {
        "customers": clean_customers(raw["customers"], log),
        "sellers": clean_sellers(raw["sellers"], log),
        "geolocation": clean_geolocation(raw["geolocation"], log),
        "category_translation": categories,
        "products": clean_products(raw["products"], categories, log),
        "orders": clean_orders(raw["orders"], log),
        "order_items": clean_order_items(raw["order_items"], log),
        "payments": clean_payments(raw["payments"], log),
        "reviews": clean_reviews(raw["reviews"], log),
    }


def save_tables(tables: dict[str, pd.DataFrame], out_dir: Path = PROCESSED_DIR) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, file_name in OUTPUT_FILES.items():
        # ISO dates and no index -> easy to load into MySQL and Power BI.
        tables[name].to_csv(out_dir / file_name, index=False, date_format="%Y-%m-%d %H:%M:%S")
        logger.info("Saved %-26s %8d rows", file_name, len(tables[name]))


def write_cleaning_report(raw: dict[str, pd.DataFrame], clean: dict[str, pd.DataFrame],
                          log: CleaningLog, path: Path) -> None:
    counts = pd.DataFrame([
        {"table": name, "raw_rows": len(raw[name]), "clean_rows": len(clean[name]),
         # negative = rows removed/aggregated, positive = rows added
         "row_change": len(clean[name]) - len(raw[name]),
         "clean_columns": clean[name].shape[1], "output_file": OUTPUT_FILES[name]}
        for name in OUTPUT_FILES
    ])
    derived = pd.DataFrame([
        ("orders", "purchase_date, purchase_year_month", "Date grain for trends"),
        ("orders", "in_analysis_window", "TRUE for 2017-01..2018-08 (complete months)"),
        ("orders", "is_revenue_order", "FALSE for canceled / unavailable"),
        ("orders", "is_valid_delivery", "delivered + has date + no sequence error"),
        ("orders", "delivery_days, estimated_delivery_days", "Days from purchase (valid deliveries only)"),
        ("orders", "delivery_delay_days, is_late", "Delivered date minus estimated date; late if > 0"),
        ("order_items", "line_total", "price + freight_value"),
        ("order_items", "is_price_outlier", "price > Q3 + 3*IQR (flag only)"),
        ("reviews", "has_comment, is_latest_for_order", "Comment present; one official review per order"),
        ("products", "product_category_name_english", "Joined from translation table"),
        ("geolocation", "sample_count", "GPS samples behind each zip prefix"),
    ], columns=["table", "column(s)", "meaning"])

    md = [
        "# Cleaning Log",
        "",
        f"_Auto-generated by `src/cleaning/pipeline.py` on {datetime.now():%Y-%m-%d %H:%M}. "
        "Raw files in `data/raw/` are never modified._",
        "",
        "Decisions and reasoning: see `docs/data_model.md` section 4.",
        "",
        "## Row counts",
        "",
        df_to_markdown(counts),
        "## Every cleaning step",
        "",
        df_to_markdown(log.to_frame()),
        "## Derived columns added",
        "",
        df_to_markdown(derived),
        "## Validation",
        "",
        "All post-cleaning checks in `src/cleaning/validation.py` passed: primary keys unique "
        "and non-null, zero foreign-key orphans (including products -> categories), no "
        "negative delivery times, valid price/installment/score ranges, exactly one "
        "official review per reviewed order.",
        "",
    ]
    path.write_text("\n".join(md), encoding="utf-8")


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    try:
        raw = load_all_raw()
    except MissingDatasetError as exc:
        logger.error(str(exc))
        return 1

    log = CleaningLog()
    clean = clean_all(raw, log)

    try:
        assert_valid(clean)        # stop BEFORE writing anything if rules are broken
    except DataValidationError as exc:
        logger.error(str(exc))
        return 2
    logger.info("Validation passed")

    save_tables(clean)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    write_cleaning_report(raw, clean, log, REPORTS_DIR / "cleaning_log.md")
    logger.info("Wrote %s", REPORTS_DIR / "cleaning_log.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
