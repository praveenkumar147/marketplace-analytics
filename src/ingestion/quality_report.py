"""Generate the Module A data quality report.

Run from the project root:
    python -m src.ingestion.quality_report

Outputs:
    reports/data_quality_report.md    human-readable report (auto-generated)
    reports/data_quality_summary.json machine-readable numbers for later modules/tests
"""
from __future__ import annotations

import json
import logging
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

from src.config import RAW_DIR, REPORTS_DIR
from src.ingestion.loader import MissingDatasetError, load_all_raw
from src.ingestion.profiler import (
    check_foreign_keys,
    check_primary_key,
    numeric_summary,
    profile_columns,
    run_validity_checks,
)
from src.ingestion.registry import TABLES

logger = logging.getLogger(__name__)


def df_to_markdown(df: pd.DataFrame, index: bool = False) -> str:
    """Minimal DataFrame -> GitHub markdown table (avoids an extra dependency)."""
    if df.empty:
        return "_(none)_\n"
    frame = df.reset_index() if index else df
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    divider = "|" + "|".join("---" for _ in frame.columns) + "|"
    body = [
        "| " + " | ".join(str(v).replace("|", "\\|") for v in row) + " |"
        for row in frame.itertuples(index=False)
    ]
    return "\n".join([header, divider, *body]) + "\n"


def dataset_facts(tables: dict[str, pd.DataFrame]) -> dict:
    """Headline facts that describe the business coverage of the dataset."""
    orders = tables["orders"]
    customers = tables["customers"]
    items = tables["order_items"]
    purchase = orders["order_purchase_timestamp"]

    orders_per_person = (
        orders.merge(customers[["customer_id", "customer_unique_id"]], on="customer_id", how="left")
        .groupby("customer_unique_id")["order_id"].nunique()
    )
    items_per_order = items.groupby("order_id")["order_item_id"].count()
    monthly = purchase.dt.to_period("M").value_counts().sort_index()

    return {
        "first_purchase": str(purchase.min()),
        "last_purchase": str(purchase.max()),
        "orders": int(orders["order_id"].nunique()),
        "customer_ids": int(customers["customer_id"].nunique()),
        "unique_customers": int(customers["customer_unique_id"].nunique()),
        "customers_with_2plus_orders": int((orders_per_person >= 2).sum()),
        "pct_customers_with_2plus_orders": round(100 * (orders_per_person >= 2).mean(), 2),
        "sellers": int(tables["sellers"]["seller_id"].nunique()),
        "products": int(tables["products"]["product_id"].nunique()),
        "categories_pt": int(tables["products"]["product_category_name"].nunique()),
        "avg_items_per_order": round(float(items_per_order.mean()), 3),
        "max_items_per_order": int(items_per_order.max()),
        "order_status_counts": orders["order_status"].value_counts().to_dict(),
        "orders_per_month": {str(k): int(v) for k, v in monthly.items()},
    }


def build_report(tables: dict[str, pd.DataFrame]) -> tuple[str, dict]:
    """Run every check and assemble (markdown_text, summary_dict)."""
    overview_rows, pk_rows, sections = [], [], []
    for name, spec in TABLES.items():
        df = tables[name]
        file_mb = (RAW_DIR / spec.file_name).stat().st_size / 1_048_576
        overview_rows.append({
            "table": name, "file": spec.file_name, "rows": len(df), "columns": df.shape[1],
            "size_mb": round(file_mb, 1), "primary_key": ", ".join(spec.primary_key) or "(none)",
        })
        pk = check_primary_key(df, spec.primary_key)
        pk_rows.append({"table": name, **pk})

        num = numeric_summary(df)
        sections.append(
            f"### `{name}`\n\n{spec.description}\n\n"
            f"{df_to_markdown(profile_columns(df))}\n"
            + (f"Numeric summary:\n\n{df_to_markdown(num, index=True)}\n" if not num.empty else "")
        )

    overview = pd.DataFrame(overview_rows)
    pk_df = pd.DataFrame(pk_rows)
    fk_df = check_foreign_keys(tables)
    rules_df = run_validity_checks(tables)
    facts = dataset_facts(tables)

    status_df = pd.DataFrame(
        sorted(facts["order_status_counts"].items(), key=lambda kv: -kv[1]),
        columns=["order_status", "orders"],
    )
    status_df["pct"] = (100 * status_df["orders"] / status_df["orders"].sum()).round(2)

    md = [
        "# Data Quality Report - Olist Raw Data",
        "",
        f"_Auto-generated by `src/ingestion/quality_report.py` on "
        f"{datetime.now():%Y-%m-%d %H:%M}. Do not edit by hand; re-run the script._",
        "",
        "Source: Brazilian E-Commerce Public Dataset by Olist "
        "(Kaggle, CC BY-NC-SA 4.0). Raw files are read-only; nothing here modifies them.",
        "",
        "## 1. Dataset overview",
        "",
        df_to_markdown(overview),
        "## 2. Business coverage",
        "",
        f"- Purchase dates: **{facts['first_purchase']}** to **{facts['last_purchase']}**",
        f"- Orders: **{facts['orders']:,}**",
        f"- `customer_id` values: **{facts['customer_ids']:,}**; real customers "
        f"(`customer_unique_id`): **{facts['unique_customers']:,}**",
        f"- Customers with 2+ orders: **{facts['customers_with_2plus_orders']:,}** "
        f"({facts['pct_customers_with_2plus_orders']}%)",
        f"- Sellers: **{facts['sellers']:,}** | Products: **{facts['products']:,}** | "
        f"Categories (Portuguese): **{facts['categories_pt']}**",
        f"- Items per order: average **{facts['avg_items_per_order']}**, "
        f"max **{facts['max_items_per_order']}**",
        "",
        "Order status distribution:",
        "",
        df_to_markdown(status_df),
        "Orders per month (purchase date):",
        "",
        df_to_markdown(pd.DataFrame(list(facts["orders_per_month"].items()),
                                    columns=["month", "orders"])),
        "## 3. Primary key checks",
        "",
        "`duplicate_key_rows` counts every row that shares its key with another row.",
        "",
        df_to_markdown(pk_df),
        "## 4. Foreign key (referential integrity) checks",
        "",
        "An orphan is a child row whose key has no matching parent row.",
        "",
        df_to_markdown(fk_df),
        "## 5. Validity and business-rule checks",
        "",
        df_to_markdown(rules_df),
        "## 6. Column profiles",
        "",
        *sections,
    ]

    summary = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "overview": overview.to_dict(orient="records"),
        "facts": facts,
        "primary_keys": pk_df.to_dict(orient="records"),
        "foreign_keys": fk_df.to_dict(orient="records"),
        "validity": rules_df.to_dict(orient="records"),
    }
    return "\n".join(md), summary


def main(output_dir: Path = REPORTS_DIR) -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    try:
        tables = load_all_raw()
    except MissingDatasetError as exc:
        logger.error(str(exc))
        return 1

    markdown, summary = build_report(tables)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "data_quality_report.md").write_text(markdown, encoding="utf-8")
    (output_dir / "data_quality_summary.json").write_text(
        json.dumps(summary, indent=2, default=str), encoding="utf-8"
    )
    logger.info("Wrote %s", output_dir / "data_quality_report.md")
    logger.info("Wrote %s", output_dir / "data_quality_summary.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
